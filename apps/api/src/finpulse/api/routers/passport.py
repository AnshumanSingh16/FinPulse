"""The FinPulse Financial Passport: a prototype, multidimensional financial-health profile.

Not a credit score. Every response carries the model's disclaimer. Scores are calculated by the
deterministic scoring engine from the analytics metrics at request time; nothing is generated by
a language model.
"""

from __future__ import annotations

from typing import Annotated

from fastapi import APIRouter, Query

from finpulse.api.deps import DataSourceDep, OrgDep
from finpulse.api.routers.entities import AsOf, EntityId
from finpulse.scoring import load_model, passport_history, with_monthly_change
from finpulse.scoring.config import ScoringModel
from finpulse.scoring.history import MAX_MONTHS
from finpulse.scoring.schemas import Passport, PassportHistory
from finpulse.services.entities import load_entity, resolve_as_of

router = APIRouter(prefix="/api/v1", tags=["passport"])


@router.get(
    "/entities/{entity_id}/passport",
    response_model=Passport,
    summary="Financial Passport (prototype financial-health profile, not a credit score)",
)
async def passport(
    entity_id: EntityId, source: DataSourceDep, org_id: OrgDep, as_of: AsOf = None
) -> Passport:
    data = await load_entity(source, org_id, entity_id)
    return with_monthly_change(data, resolve_as_of(data, as_of), load_model())


@router.get(
    "/entities/{entity_id}/passport/history",
    response_model=PassportHistory,
    summary="Financial Passport at each month-end, with each change explained",
)
async def history(
    entity_id: EntityId,
    source: DataSourceDep,
    org_id: OrgDep,
    as_of: AsOf = None,
    months: Annotated[
        int, Query(ge=1, le=MAX_MONTHS, description="Number of points, including as_of")
    ] = 12,
) -> PassportHistory:
    data = await load_entity(source, org_id, entity_id)
    return passport_history(data, resolve_as_of(data, as_of), months, load_model())


@router.get(
    "/meta/passport-model",
    response_model=ScoringModel,
    tags=["meta"],
    summary="The scoring configuration: dimensions, weights, curves, bands, disclaimer",
)
async def passport_model() -> ScoringModel:
    return load_model()
