"""
Proactive CFO alerts: what the owner should know before they ask.

Each alert comes from an engine result, carries its proof (records, arithmetic, assumptions, what can't be verified)
and offers practical next steps. Nothing here is generated by a language model.
"""

from __future__ import annotations

import pandas as pd

from finpilot.engine.common import fmt_inr, money, prepare_ledger, ts

RISE_PCT = 25
RISE_MIN = 10_000
SALES_DROP_PCT = 15


def _l(lang: str, en: str, hi: str, **kw) -> str:
    return (hi if lang == "hi" else en).format(**kw)


def _ev(title, formula, method, assumptions, unverified, records, period) -> dict:
    return {"title": title, "formula": formula, "method": method, "assumptions": assumptions, "unverified": unverified,
            "limitations": [], "record_ids": list(dict.fromkeys(records)), "record_count": len(set(records)), "period": period}


def _next_week(o7: dict, lang: str) -> dict | None:
    if not o7 or o7.get("status") != "ok":
        return None
    bills = [i for i in o7["items"] if i["group"] in ("bill", "regular_out") and i["included"]]
    ins = [i for i in o7["items"] if i["group"] in ("collection", "regular_in") and i["included"]]
    out_total = money(-sum(i["amount"] for i in bills))
    in_total = money(sum(i["amount"] for i in ins))
    typ = {w["key"]: w["amount"] for w in o7["waterfall"]}
    available = money(o7["start"] + in_total + typ.get("typical_in", 0))
    short = o7["lowest"] < o7["safety"]
    exceeds = out_total > available
    if not (short or exceeds):
        return None
    tone = "bad" if exceeds or o7["lowest"] < 0 else "caution"
    title = (_l(lang, "Your bills next week may exceed the cash you'll have", "अगले हफ़्ते के बिल आपके पास के कैश से ज़्यादा हो सकते हैं") if exceeds
             else _l(lang, "Cash dips below your cushion next week", "अगले हफ़्ते कैश आपकी गद्दी से नीचे जाएगा"))
    detail = _l(lang, "{bills} of bills and salaries are due by {end}. You have {cash} today and expect {inn} in. Lowest point: {low} on {d} (cushion {cush}).",
                "{end} तक {bills} के बिल और तनख़्वाह देय हैं। आज आपके पास {cash} है और {inn} आने की उम्मीद है। सबसे कम: {d} को {low} (गद्दी {cush})।",
                bills=fmt_inr(out_total), end=o7["end_date"], cash=fmt_inr(o7["start"]), inn=fmt_inr(in_total + typ.get("typical_in", 0)),
                low=fmt_inr(o7["lowest"]), d=o7["lowest_date"], cush=fmt_inr(o7["safety"]))
    formula = [f"Cash today {fmt_inr(o7['start'])}"] + [f"+ {i['label']} ({i['date']}): {fmt_inr(i['amount'])}" for i in ins[:8]]
    if typ.get("typical_in"):
        formula.append(f"+ day-to-day sales: {fmt_inr(typ['typical_in'])}")
    formula += [f"− {i['label']} ({i['date']}): {fmt_inr(-i['amount'])}" for i in bills[:10]]
    if typ.get("typical_out"):
        formula.append(f"− day-to-day costs: {fmt_inr(-typ['typical_out'])}")
    formula.append(f"= {fmt_inr(o7['end'])} on {o7['end_date']}; lowest {fmt_inr(o7['lowest'])} on {o7['lowest_date']}.")
    return {"id": "next_week", "tone": tone, "title": title, "detail": detail,
            "evidence": _ev(title, formula, o7["evidence"]["method"], o7["evidence"]["assumptions"], o7["evidence"]["unverified"],
                            [i["id"] for i in bills + ins if i.get("record")], [o7["as_of"], o7["end_date"]]),
            "actions": [{"label": _l(lang, "Show me the fix", "हल दिखाओ"), "do": "fix"}, {"label": _l(lang, "Cash in 2 weeks", "2 हफ़्ते बाद कैश"), "do": "outlook"}]}


def _overdue(plan: dict, obligations, as_of, lang: str) -> dict | None:
    col = [m for m in plan.get("moves", []) if m["kind"] == "collect"]
    if not col:
        return None
    total = money(sum(m["amount"] for m in col))
    top = max(col, key=lambda m: m["amount"])
    ids = [i for m in col for i in m["items"]]
    o = obligations[obligations["item_id"].isin(ids)] if obligations is not None else pd.DataFrame()
    formula = [f"{r.item_id} · {r.counterparty}: {fmt_inr(r.amount)}, due {pd.Timestamp(r.due_date).date()} ({int((ts(as_of) - pd.Timestamp(r.due_date)).days)} days late)"
               for r in o.sort_values("due_date").itertuples()] + [f"Total overdue: {fmt_inr(total)}"]
    title = _l(lang, "{amt} of customer payments are overdue", "ग्राहकों के {amt} बकाया हैं", amt=fmt_inr(total))
    detail = _l(lang, "Biggest: {who}, {amt}, {d} days late. It isn't counted in your forecast until they pay.",
                "सबसे बड़ा: {who}, {amt}, {d} दिन देर। जब तक वे नहीं देते, यह आपके अनुमान में नहीं गिना गया।",
                who=top["party"], amt=fmt_inr(top["amount"]), d=top.get("days_late", 0))
    return {"id": "overdue", "tone": "bad" if top.get("days_late", 0) > 30 else "caution", "title": title, "detail": detail,
            "evidence": _ev(title, formula, "Overdue = invoices still marked pending whose due date has passed.",
                            ["An invoice marked pending is unpaid as of today."],
                            ["Whether the customer disputes any invoice or has already paid without it being recorded."], ids, None),
            "actions": [{"label": _l(lang, "Draft a reminder to {who}", "{who} को याद दिलाओ", who=top["party"]), "q": _l(lang, "Remind {who}", "{who} को याद दिलाओ", who=top["party"])}]}


def _rising_costs(ledger, as_of, lang: str) -> list[dict]:
    df = prepare_ledger(ledger)
    a = ts(as_of)
    m_end = a if a == a + pd.offsets.MonthEnd(0) else (a.replace(day=1) - pd.Timedelta(days=1))
    m_start = m_end.replace(day=1)
    b_start = (m_start - pd.DateOffset(months=3)).normalize()
    op = df[(df["cls"] == "operating") & (df["direction"] == "out")]
    last = op[(op["date"] >= m_start) & (op["date"] <= m_end)]
    before = op[(op["date"] >= b_start) & (op["date"] < m_start)]
    if not len(before):
        return []
    lv = last.groupby("category")["amount"].sum()
    bv = before.groupby("category")["amount"].sum() / 3
    out = []
    for cat, now in lv.items():
        avg = float(bv.get(cat, 0))
        rise = now - avg
        if avg <= 0 or rise < RISE_MIN or rise / avg * 100 < RISE_PCT:
            continue
        rows = last[last["category"] == cat].sort_values("amount", ascending=False)
        pct = round(rise / avg * 100)
        title = (_l(lang, "{cat} costs are {x}× a usual month", "{cat} का खर्च आम महीने का {x} गुना", cat=cat, x=f"{now / avg:.1f}".rstrip("0").rstrip("."))
                 if pct > 200 else _l(lang, "{cat} costs are up {p}%", "{cat} का खर्च {p}% बढ़ा", cat=cat, p=pct))
        detail = _l(lang, "{now} in {m} vs a usual {avg} a month (the 3 months before). Biggest payment: {big} to {who}.",
                    "{m} में {now}, जबकि आम तौर पर महीने का {avg} (पिछले 3 महीने)। सबसे बड़ा भुगतान: {who} को {big}।",
                    now=fmt_inr(now), m=f"{m_start:%b %Y}", avg=fmt_inr(avg), big=fmt_inr(rows.iloc[0]["amount"]), who=rows.iloc[0]["counterparty"])
        formula = [f"{m_start:%b %Y}: {len(rows)} payment(s) = {fmt_inr(now)}",
                   f"Usual month = {fmt_inr(avg * 3)} over {b_start:%b}–{(m_start - pd.Timedelta(days=1)):%b %Y} ÷ 3 = {fmt_inr(avg)}",
                   f"Rise = {fmt_inr(now)} − {fmt_inr(avg)} = {fmt_inr(rise)} ({pct}%)"]
        out.append({"id": f"costs:{cat}", "tone": "caution", "title": title, "detail": detail, "rise": money(rise),
                    "evidence": _ev(title, formula, "Operating payments in the category, last full month vs the average of the three months before.",
                                    ["Payments are counted in the month they leave the bank."],
                                    ["Whether this is a price rise, more volume or a one-off (e.g. a yearly payment) — the bank line doesn't say.",
                                     "Whether it is paying for something that will bring sales later."],
                                    list(rows["txn_id"]), [str(m_start.date()), str(m_end.date())]),
                    "actions": [{"label": _l(lang, "Look into it", "जाँच करो"), "q": _l(lang, "Why did I spend so much on {cat}?", "{cat} पर इतना खर्च क्यों हुआ?", cat=cat)}]})
    return sorted(out, key=lambda x: -x["rise"])[:2]


def _sales_drop(sc: dict, lang: str) -> dict | None:
    if not sc or sc.get("status") != "ok" or sc["sales"]["change_pct"] is None or sc["sales"]["change_pct"] > -SALES_DROP_PCT:
        return None
    s = sc["sales"]
    late = [c for c in sc["customers"] if c["change"] < 0 and c["unpaid_due"]]
    title = _l(lang, "Sales received are {p}% lower than last month", "मिली बिक्री पिछले महीने से {p}% कम है", p=round(-s["change_pct"]))
    detail = (_l(lang, "{cur} vs {prev}. Part of it is late money: {who} owes {amt} that is due.", "{cur} बनाम {prev}। इसमें कुछ देर से आने वाला पैसा है: {who} पर {amt} देय है।",
                 cur=fmt_inr(s["current"]), prev=fmt_inr(s["previous"]), who=late[0]["party"], amt=fmt_inr(late[0]["unpaid_due"])) if late
              else _l(lang, "{cur} vs {prev}. Ask me why — I'll trace it customer by customer.", "{cur} बनाम {prev}। वजह पूछें — मैं ग्राहक-दर-ग्राहक देखूँगा।",
                      cur=fmt_inr(s["current"]), prev=fmt_inr(s["previous"])))
    ev = sc["evidence"]
    return {"id": "sales_drop", "tone": "caution", "title": title, "detail": detail,
            "evidence": _ev(title, ev.get("formula") or [],
                            ev["method"], ev["assumptions"], ev["unverified"], ev["record_ids"], ev.get("period")),
            "actions": [{"label": _l(lang, "Why are my sales less?", "बिक्री कम क्यों है?"), "q": _l(lang, "Why are my sales less this month?", "इस महीने बिक्री कम क्यों है?")}]}


def cfo_alerts(plan: dict, ledger, obligations, as_of, o7: dict | None, sales: dict | None, lang: str = "en") -> list[dict]:
    out = [a for a in (_next_week(o7, lang), _overdue(plan, obligations, as_of, lang), _sales_drop(sales, lang)) if a]
    out += _rising_costs(ledger, as_of, lang)
    rank = {"bad": 0, "caution": 1, "info": 2}
    return sorted(out, key=lambda a: rank.get(a["tone"], 3))
