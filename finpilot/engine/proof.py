"""
"Prove it": for any recommendation, the records it rests on, the arithmetic, the assumptions and what can't be verified.

Every number here is recomputed from the ledger, the invoices and bills, and the plan's own forecast — the same
figures the move card shows. Nothing is generated by a language model.
"""

from __future__ import annotations

import pandas as pd

from finpilot.engine.common import fmt_inr, money, prepare_ledger, ts

PAUSE_DAYS = 60
OD_RATE = 0.14


def _tightest(plan: dict, new_lowest: float | None) -> list[str]:
    b = plan["baseline"]
    if new_lowest is None:
        return []
    return [f"Tightest day in the next 90 days without this move: {fmt_inr(b['lowest'])} on {b['lowest_date']}.",
            f"With this move alone: {fmt_inr(new_lowest)} — {'+' if new_lowest >= b['lowest'] else ''}{fmt_inr(new_lowest - b['lowest'])}."]


def _history(obligations: pd.DataFrame | None, party: str) -> tuple[list[str], list[str]]:
    """A customer's past invoices: how late they usually pay. Returns (lines, record ids)."""
    if obligations is None or not len(obligations):
        return [], []
    o = obligations[(obligations["kind"] == "receivable") & (obligations["counterparty"] == party) & (obligations["status"] == "paid")].copy()
    o = o[o["paid_date"].notna()]
    if not len(o):
        return [f"{party} has no paid invoices on record, so their usual payment delay isn't known."], []
    delay = (pd.to_datetime(o["paid_date"]) - pd.to_datetime(o["due_date"])).dt.days
    lines = [f"Past payments from {party}: {len(o)} invoice(s) paid, a median of {int(delay.median())} day(s) after the due date "
             f"(earliest {int(delay.min())}, latest {int(delay.max())})."]
    return lines, list(o.sort_values("due_date")["item_id"].tail(8))


def prove_move(m: dict, plan: dict, ledger: pd.DataFrame, obligations: pd.DataFrame | None, as_of) -> dict:
    as_of = ts(as_of)
    k = m["kind"]
    records: list[str] = list(m.get("items") or [])
    formula: list[str] = []
    assumptions: list[str] = []
    unverified: list[str] = []
    if k == "collect":
        o = obligations[obligations["item_id"].isin(records)] if obligations is not None else pd.DataFrame()
        for r in o.itertuples():
            formula.append(f"{r.item_id}: {fmt_inr(r.amount)}, due {pd.Timestamp(r.due_date).date()} — {int((as_of - pd.Timestamp(r.due_date)).days)} days late.")
        formula.append(f"Total owed: {' + '.join(fmt_inr(a) for a in o['amount'])} = {fmt_inr(m['amount'])}." if len(o) > 1 else f"Total owed: {fmt_inr(m['amount'])}.")
        formula += _tightest(plan, m.get("new_lowest"))
        hist, ids = _history(obligations, m["party"])
        formula += hist
        records += ids
        assumptions += ["After a reminder they pay the full amount within 7 days.",
                        "Overdue invoices are NOT counted as incoming in the forecast until you approve this move."]
        unverified += [f"Whether {m['party']} has the money, or disputes anything on these invoices.",
                       "Whether they'll pay in full or in parts.",
                       "That the invoices reached the right person — FinPilot only sees your records."]
    elif k == "pause":
        df = prepare_ledger(ledger)
        start = (as_of - pd.DateOffset(months=3)).normalize()
        rows = df[(df["category"] == m["party"]) & (df["direction"] == "out") & (df["date"] > start) & (df["date"] <= as_of)]
        records += list(rows.sort_values("date", ascending=False)["txn_id"].head(30))
        monthly = m.get("monthly") or 0
        formula += [f"{m['party']} paid in the last 3 months: {len(rows)} payment(s), {fmt_inr(rows['amount'].sum())} in total.",
                    f"Monthly average used: {fmt_inr(monthly)} (the forecast's run rate for this category).",
                    f"Kept in the bank over {PAUSE_DAYS} days: {fmt_inr(monthly)} × 12 ÷ 365 × {PAUSE_DAYS} = {fmt_inr(m['amount'])}."]
        formula += _tightest(plan, m.get("new_lowest"))
        assumptions += [f"The spend can stop completely for {PAUSE_DAYS} days and then resumes as before."]
        unverified += ["Whether any of this is already committed (booked ads, contracts, standing instructions).",
                       "What pausing does to sales — for example, less marketing can mean fewer new customers later." if m["party"] == "Marketing"
                       else "Whether the household can manage without these drawings."]
    elif k == "defer":
        formula += [f"Bill {', '.join(records)}: {fmt_inr(m['amount'])} due {m.get('from_date')} → asked to move to {m.get('to_date')}.",
                    f"Between those dates the balance is higher by {fmt_inr(m['amount'])}; after {m.get('to_date')} it is the same as before."]
        formula += _tightest(plan, m.get("new_lowest"))
        assumptions += ["The supplier agrees to 21 more days, with no late fee."]
        unverified += [f"Whether {m['party']} agrees, and whether it affects their prices or your credit with them.",
                       "Any late fee or interest in your agreement with them."]
    elif k == "reserve":
        df = prepare_ledger(ledger)
        gst = df[(df["cls"] == "tax_remittance") & (df["direction"] == "out") & df["category"].astype(str).str.contains("GST", case=False)]
        records += list(gst.sort_values("date", ascending=False)["txn_id"].head(6))
        if len(gst):
            last = gst.sort_values("date").tail(6)
            formula.append(f"Your last {len(last)} GST payment(s): {', '.join(fmt_inr(a) for a in last['amount'])}.")
        formula += [f"Set aside: {fmt_inr(m['amount'])}, due {m.get('due')}.",
                    "This doesn't change the balance (the GST is already in the forecast); it lowers 'safe to spend' so the money isn't used by mistake."]
        assumptions += ["This month's GST is about the same as a typical recent month."]
        unverified += ["Your actual GST for this month — it depends on this month's sales and input tax credit, which need your GST return data (GSTR-1/3B)."]
    elif k == "borrow":
        odds = plan.get("odds", {})
        sugg = odds.get("suggested") or {}
        interest = money(m["amount"] * OD_RATE * 90 / 365)
        formula += [f"In the worst 10% of 1,000 simulated futures with the plan, the tightest day falls to about {fmt_inr(sugg.get('bad_case_lowest', 0))}.",
                    f"Backup = your cushion {fmt_inr(plan['safety'])} − that bad-case low, rounded up: {fmt_inr(m['amount'])}.",
                    f"Cost only if all of it is used for 90 days: {fmt_inr(m['amount'])} × 14% × 90 ÷ 365 = {fmt_inr(interest)}.",
                    f"Chance you stay safe: {round((sugg.get('p_safe') or 0) * 100)}% with the plan → {round((m.get('odds_with_plan') or 0) * 100)}% with the backup ready."]
        assumptions += ["An overdraft at about 14% a year, interest charged only on what is used."]
        unverified += ["Whether your bank will approve it, and the actual rate, fees and security they ask for."]
    elif k == "discount":
        formula += [f"Invoice {', '.join(records)}: {fmt_inr(m.get('invoice') or 0)}, due {m.get('from_date')}.",
                    f"2% off: {fmt_inr(m.get('invoice') or 0)} × 2% = {fmt_inr(m.get('cost') or 0)}; paid by {m.get('to_date')} instead."]
        formula += _tightest(plan, m.get("new_lowest"))
        assumptions += ["They accept the offer (7 in 10 do in the simulation) and pay on the new date."]
        unverified += [f"Whether {m['party']} takes the discount."]
    claim = m.get("title") or m["id"]
    return {
        "status": "ok", "move_id": m["id"], "title": "Show me why", "claim": claim,
        "formula": formula, "method": m.get("detail", ""),
        "assumptions": assumptions, "unverified": unverified,
        "limitations": ["A move is an option, not a promise — the other party decides."] if k in ("collect", "defer", "discount") else [],
        "record_ids": list(dict.fromkeys(records)), "period": None,
    }
